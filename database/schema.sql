BEGIN;

CREATE TABLE comunidades (
  id_comunidad integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  municipio text NOT NULL,
  descripcion text,
  latitud double precision NOT NULL CHECK (latitud BETWEEN -90 AND 90),
  longitud double precision NOT NULL CHECK (longitud BETWEEN -180 AND 180)
);

CREATE TABLE organizaciones (
  id_organizacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  descripcion text,
  contacto_institucional text NOT NULL
);

CREATE UNIQUE INDEX organizaciones_contacto_unico
  ON organizaciones (LOWER(TRIM(contacto_institucional)));

CREATE TABLE necesidades (
  id_necesidad integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comunidad_id integer NOT NULL REFERENCES comunidades (id_comunidad),
  categoria text NOT NULL,
  descripcion text NOT NULL,
  cantidad_estimada bigint NOT NULL CHECK (cantidad_estimada >= 0),
  fecha_registro timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  estado_verificacion text NOT NULL DEFAULT 'pendiente'
    CHECK (estado_verificacion IN ('pendiente', 'verificado', 'rechazado'))
);

CREATE TABLE usuarios (
  id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  correo text NOT NULL,
  contrasena_hash text NOT NULL,
  rol text NOT NULL CHECK (rol IN ('administrador', 'organizacion')),
  organizacion_id integer REFERENCES organizaciones (id_organizacion),
  fecha_creacion timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (
    (rol = 'administrador' AND organizacion_id IS NULL)
    OR (rol = 'organizacion' AND organizacion_id IS NOT NULL)
  )
);

CREATE UNIQUE INDEX usuarios_correo_unico ON usuarios (LOWER(correo));

CREATE TABLE ayudas (
  id_ayuda integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comunidad_id integer NOT NULL REFERENCES comunidades (id_comunidad),
  necesidad_id integer REFERENCES necesidades (id_necesidad),
  organizacion_id integer NOT NULL REFERENCES organizaciones (id_organizacion),
  tipo_ayuda varchar(80) NOT NULL,
  cantidad integer NOT NULL CHECK (cantidad > 0),
  fecha date NOT NULL,
  estado text NOT NULL DEFAULT 'programada'
    CHECK (estado IN ('programada', 'entregada')),
  fecha_creacion timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMIT;
